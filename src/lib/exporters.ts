export function ltspiceCir(project: Project): string {
  const filter = project.protection;
  const cap = analyzeCapacitance(project.capacitance);
  const bulk = cap.recommended;
  const cBulk = bulk?.cEffectiveF ?? cap.cMinF;
  const esr = bulk?.esrOhm ?? cap.esrMaxOhm;
  const iBase = Math.max(0, cap.iPeak > 0 ? 0.16 : 0);
  const iPulse = cap.iPeak;
  const burst = project.capacitance.burstUs * 1e-6;
  const frame = 4.615e-3;
  const lines = [
    "* HardwarePowerStudio — 24 V EMI filter, 3.8 V bulk, LTE/GSM pulse",
    "* Open in LTspice. .tran 5m is active. For the filter, change the last directive to .ac dec 40 100 10Meg",
    `Vbat in 0 DC ${filter.vin}`,
    `Lf in n1 ${filter.lH}`,
    `Rl n1 ncap ${filter.rlOhm}`,
    `Cf ncap 0 ${filter.cF}`,
    `Rd ncap nd ${Math.max(filter.rdOhm, 1e-6)}`,
    `Cd nd 0 ${Math.max(filter.cdF, 1e-12)}`,
    `* Constant-power buck input, Pout/eta drawn from the filter node`,
    `Bload ncap 0 I=${filter.pout}/(${filter.eta}*MAX(V(ncap),1))`,
    `Vreg vreg 0 DC ${project.capacitance.vNom}`,
    `Resr vreg vcap ${Math.max(esr, 1e-4)}`,
    `Cbulk vcap 0 ${Math.max(cBulk, 1e-6)}`,
    `* Connected modem plus the 577 us TX slot inside a 4.615 ms GSM frame`,
    `Iltx vcap 0 PULSE(${iBase} ${iPulse} 1m 1u 1u ${burst} ${frame})`,
    ".tran 5m",
    ".end",
    ""
  ];
  return lines.join("\n");
}

export function ltspiceAsc(project: Project): string {
  const filter = project.protection;
  const v = project.capacitance.vNom;
  return [
    "Version 4",
    "SHEET 1 1180 720",
    "WIRE 160 128 80 128",
    "WIRE 320 128 240 128",
    "WIRE 320 224 320 128",
    "WIRE 80 224 80 128",
    "WIRE 80 320 80 304",
    "WIRE 320 320 320 304",
    "FLAG 80 320 0",
    "FLAG 320 320 0",
    "FLAG 320 128 NCAP",
    "SYMBOL voltage 80 208 R0",
    "SYMATTR InstName Vbat",
    `SYMATTR Value ${filter.vin}`,
    "SYMBOL ind 176 112 R270",
    "SYMATTR InstName Lf",
    `SYMATTR Value ${filter.lH * 1e6}u`,
    "SYMBOL res 256 112 R270",
    "SYMATTR InstName Rl",
    `SYMATTR Value ${filter.rlOhm}`,
    "SYMBOL cap 304 224 R0",
    "SYMATTR InstName Cf",
    `SYMATTR Value ${filter.cF * 1e6}u`,
    "SYMBOL voltage 640 208 R0",
    "SYMATTR InstName Vreg",
    `SYMATTR Value ${v}`,
    "SYMBOL current 800 208 R0",
    "SYMATTR InstName Iltx",
    `SYMATTR Value PULSE(0.16 ${project.capacitance.iPeak} 1m 1u 1u ${project.capacitance.burstUs}u 4.615m)`,
    "TEXT 80 400 Left 2 !.tran 5m",
    "TEXT 80 440 Left 2 ; Generated by HardwarePowerStudio. The .cir netlist is the runnable deck.",
    ""
  ].join("\n");
}

function csvEscape(value: string | number): string {
  const text = String(value);
  if (text.includes(",") || text.includes('"')) return `"${text.replaceAll('"', '""')}"`;
  return text;
}

export function altiumRulesCsv(project: Project): string {
  return formatAltiumRulesCsv(altiumDesignRules(project));
}

export interface BomRow {
  manufacturer: string;
  mpn: string;
  qty: string;
  value: string;
  description: string;
}

export function bomRows(project: Project): BomRow[] {
  const cap = analyzeCapacitance(project.capacitance);
  const bulk = cap.recommended;
  return [
    { manufacturer: "Texas Instruments", mpn: "LMR36520", qty: "1", value: "65 V 2 A", description: "3.8 V and 5 V synchronous bucks, confirm the orderable frequency" },
    { manufacturer: "Texas Instruments", mpn: "LM74700-Q1", qty: "1", value: "ideal diode", description: "Reverse-polarity controller, external N-MOSFET" },
    { manufacturer: "Vishay", mpn: project.protection.tvsId, qty: "1", value: project.protection.tvsId, description: "GLV TVS, 10/1000 us" },
    { manufacturer: "STMicroelectronics", mpn: "VNQ7050AJ", qty: "1", value: "4x 50 mohm", description: "VCU high-side: fan, pump, brake, shutdown" },
    { manufacturer: "Infineon", mpn: "BTS7008-2EPA", qty: "1", value: "2x 8.8 mohm", description: "Accumulator fan high-side" },
    {
      manufacturer: "Coilcraft",
      mpn: project.magnetics.inductorId === "sized" ? "sized-in-tool" : project.magnetics.inductorId,
      qty: "2",
      value: `${project.magnetics.dcrMo} mohm DCR if sized`,
      description: "Buck inductors"
    },
    {
      manufacturer: bulk?.polymerName ? "Panasonic" : "Murata",
      mpn: bulk?.description ?? "bulk",
      qty: "1",
      value: bulk ? `${(bulk.cEffectiveF * 1e6).toFixed(0)} uF eff` : "see cap tool",
      description: "LTE bulk network"
    },
    {
      manufacturer: "Murata",
      mpn: `${project.magnetics.mlccCase} ${project.magnetics.cNomUf}uF ${project.magnetics.vRated}V`,
      qty: String(project.magnetics.mlccCount),
      value: project.magnetics.mlccDielectric,
      description: "Buck output ceramics, apply the DC-bias derating"
    }
  ];
}

export function bomCsv(project: Project): string {
  const header = "Manufacturer,MPN,Qty,Value,Description";
  const rows = bomRows(project).map((row) => [row.manufacturer, row.mpn, row.qty, row.value, row.description]);
  return [header, ...rows.map((row) => row.map(csvEscape).join(","))].join("\n") + "\n";
}

export function bomDocument(project: Project) {
  return {
    project: project.name,
    filename: "power-bom.csv",
    csv: bomCsv(project),
    rows: bomRows(project)
  };
}

export function designReviewMarkdown(project: Project): string {
  const power = analyzePower(project.rails, project.loads, project.traceRiseC);
  const regulator = analyzeRegulator(project.regulator);
  const cap = analyzeCapacitance(project.capacitance);
  const protection = analyzeProtection(project.protection);
  const harness = analyzeHarness(project.harness);
  const pcb = analyzePcb(project.pcb);
  const analog = analyzeAnalog(project.analog);
  const can = analyzeCan(project.can);
  const magnetics = analyzeInductor(project.regulator.vin, project.regulator.vout, project.regulator.iout, project.regulator.fswKhz * 1e3, project.magnetics);
  const mlcc = analyzeMlcc(magnetics.dI, project.regulator.fswKhz * 1e3, project.magnetics);
  const vmin = cap.recommendedSim?.vMin;
  const lines = [
    `# ${project.name}`,
    "",
    "Formula Student design-review dossier generated by HardwarePowerStudio.",
    "",
    "## Power budget",
    "",
    `- Mission input ${power.scenarios.mission.inputPowerW.toFixed(2)} W, RMS ${power.scenarios.mission.inputRmsA.toFixed(3)} A.`,
    `- Peak coincident current ${power.scenarios.peak.inputPeakA.toFixed(3)} A. Fuse ${power.fuse.ratingA} A, loading ${power.fuse.loadingPct.toFixed(0)}% of rating at the mission RMS.`,
    "",
    "## Regulator",
    "",
    regulator.valid
      ? `- ${project.regulator.architecture} ${project.regulator.vin} V to ${project.regulator.vout} V at ${project.regulator.iout} A. Junction ${regulator.tj.toFixed(1)} °C, efficiency ${regulator.efficiencyPct.toFixed(1)}%, loss ${regulator.pLossW.toFixed(3)} W. Margin to the 115 °C shutdown line is ${(115 - regulator.tj).toFixed(1)} °C.`
      : "- Regulator inputs are outside the regulating region.",
    magnetics.valid
      ? `- Inductor ${(magnetics.lH * 1e6).toFixed(2)} µH, Ipeak ${magnetics.iPeak.toFixed(3)} A, Isat minimum ${magnetics.iSatMin.toFixed(3)} A, copper ${(magnetics.pCopper * 1e3).toFixed(0)} mW, core ${(magnetics.pCore * 1e3).toFixed(0)} mW.`
      : "- Inductor sizer has no valid CCM point.",
    `- MLCC effective ${(mlcc.cEffectiveF * 1e6).toFixed(2)} µF (${(mlcc.retention * 100).toFixed(0)}% of nameplate). Output ripple ${(mlcc.rippleV * 1e3).toFixed(1)} mV.`,
    "",
    "## Input protection",
    "",
    `- ${protection.tvs.part.id} clamps at ${protection.tvs.part.vc} V. Margin to ${protection.tvs.buck?.mpn ?? "the buck"} is ${protection.tvs.marginV.toFixed(1)} V. Standoff ${protection.tvs.standoffOk ? "holds" : "conducts"} at ${project.protection.vSystemMax} V.`,
    `- Middlebrook peak |Zout|/|Zin| = ${protection.peakRatio.toFixed(3)}. ${protection.stable ? "At least 20 dB of margin." : "The filter is not damped to 20 dB."}`,
    `- Coil energy ${(protection.tvs.energyJ * 1e3).toFixed(2)} mJ against a ${protection.tvs.energyRatingJ.toFixed(2)} J rectangular rating.`,
    "",
    "## Harness and fuses",
    "",
    ...harness.channels.map(
      (row) =>
        `- ${row.channel.name}: ${row.dropV.toFixed(3)} V round trip, wire rise ${row.wireRiseC.toFixed(1)} °C, fuse I²t ${row.fuseI2t.toFixed(0)} A²s ${row.fuseCoordinates ? "below" : "ABOVE"} wire I²t ${row.wireI2t.toFixed(0)} A²s. Package ${row.tjC.toFixed(0)} °C.`
    ),
    "",
    "## LTE bulk",
    "",
    `- Brownout ${cap.vBrownout.toFixed(3)} V. Recommended network: ${cap.recommended?.description ?? "none"}.`,
    vmin !== undefined ? `- Simulated minimum during the burst is ${vmin.toFixed(3)} V, so the droop margin is ${((vmin - cap.vBrownout) * 1e3).toFixed(0)} mV.` : "- No bulk transient was simulated.",
    "",
    "## PCB",
    "",
    `- External ${pcb.externalWidthMm.toFixed(2)} mm and internal ${pcb.internalWidthMm.toFixed(2)} mm at ${project.pcb.currentA} A, ${project.pcb.oz} oz, ${project.pcb.riseC} °C.`,
    `- ${pcb.viaCount} vias of ${project.pcb.viaDrillMm} mm for ${project.pcb.iPeak} A at 0.5 °C. Thermal array θJA ${pcb.thermal.thetaJa.toFixed(2)} °C/W.`,
    `- USB ${pcb.usb.zDiff.toFixed(1)} Ω at W ${(pcb.usb.wM * 1e3).toFixed(3)} mm / S ${(pcb.usb.sM * 1e3).toFixed(3)} mm on ${pcb.stack.id}.`,
    `- CAN ${pcb.can.zDiff.toFixed(1)} Ω at W ${(pcb.can.wM * 1e3).toFixed(3)} mm / S ${(pcb.can.sM * 1e3).toFixed(3)} mm.`,
    `- 50 Ω CPWG width ${(pcb.cpwM * 1e3).toFixed(3)} mm with a 0.15 mm gap.`,
    "",
    "## Analog and CAN",
    "",
    `- Divider R1 ${analog.divider.r1.toFixed(0)} Ω, R2 ${analog.divider.r2.toFixed(0)} Ω, droop ${analog.divider.droopLsb.toFixed(3)} LSB, cutoff ${(analog.divider.f3dbHz / 1e3).toFixed(2)} kHz.`,
    `- CAN sample ${(can.timing.samplePoint * 100).toFixed(2)}%, error ${can.timing.ppm.toFixed(1)} ppm, bus ${project.can.busLengthM} m.`,
    "",
    "## What a judge should take from this",
    "",
    "Every watt, degree, ohm and ampere-squared-second above is the same function the workbench plots. The fuse is coordinated when its melting I²t is below the IEC adiabatic limit of the wire. The input filter is acceptable when the Middlebrook ratio stays under 0.1. The TVS is acceptable when its clamp is below the downstream absolute maximum and its standoff is above the system maximum.",
    ""
  ];
  return lines.join("\n");
}

export function designReviewHtml(project: Project): string {
  const body = designReviewMarkdown(project)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .split("\n")
    .map((line) => {
      if (line.startsWith("# ")) return `<h1>${line.slice(2)}</h1>`;
      if (line.startsWith("## ")) return `<h2>${line.slice(3)}</h2>`;
      if (line.startsWith("- ")) return `<li>${line.slice(2)}</li>`;
      if (line === "") return "";
      return `<p>${line}</p>`;
    })
    .join("\n");
  return `<!DOCTYPE html><html><head><meta charset="utf-8"><title>${project.name}</title>
<style>body{font-family:IBM Plex Sans,sans-serif;max-width:800px;margin:2rem auto;color:#111;line-height:1.45} h1{font-size:1.4rem} h2{font-size:1.05rem;margin-top:1.4rem} li{margin:0.2rem 0}</style>
</head><body>${body}<p>Print this page to PDF for the design binder.</p></body></html>`;
}

export function exportBundle(project: Project): Record<string, string> {
  return {
    "hardware-power.cir": ltspiceCir(project),
    "hardware-power.asc": ltspiceAsc(project),
    "altium-rules.csv": altiumRulesCsv(project),
    "power-bom.csv": bomCsv(project),
    "design-review.md": designReviewMarkdown(project),
    "design-review.html": designReviewHtml(project)
  };
}
